// WorldForge - exports the vault as a static wiki website (real HTML pages you can
// host free on GitHub Pages / Netlify / Cloudflare Pages, or just open locally).

const fs = require('fs');
const path = require('path');
const { renderMarkdown, slugFor, esc } = require('./md');

function write(p, content) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
}

